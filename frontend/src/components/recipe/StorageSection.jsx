const PLACES = [
  {
    key: 'fridge',
    label: 'Frigorifero',
    icon: (
      <svg className="w-6 h-6" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="1.75" aria-hidden>
        <rect x="6" y="3" width="12" height="18" rx="2" />
        <path d="M6 10h12M9 6v2M9 13v3" strokeLinecap="round" />
      </svg>
    )
  },
  {
    key: 'freezer',
    label: 'Congelatore',
    icon: (
      <svg className="w-6 h-6" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="1.75" aria-hidden>
        <path
          d="M12 3v18M4.2 7.5l15.6 9M4.2 16.5l15.6-9M9.5 4.5 12 7l2.5-2.5M9.5 19.5 12 17l2.5 2.5"
          strokeLinecap="round"
          strokeLinejoin="round"
        />
      </svg>
    )
  },
  {
    key: 'room',
    label: 'Temperatura ambiente',
    icon: (
      <svg className="w-6 h-6" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="1.75" aria-hidden>
        <path d="M10 14.5V5a2 2 0 1 1 4 0v9.5a4 4 0 1 1-4 0Z" strokeLinejoin="round" />
        <path d="M12 9v7" strokeLinecap="round" />
      </svg>
    )
  }
]

/**
 * "Come conservarla" — storage advice generated by Gemini when the recipe is saved.
 * pending: generation is running in the background right after a save.
 */
export default function StorageSection({ storage, pending = false, loading = false, error = null, onGenerate, id }) {
  const hasData = Boolean(storage && (storage.fridge?.how || storage.freezer?.how || storage.room?.how))

  return (
    <section id={id} className="card p-5 sm:p-6 scroll-mt-24">
      <div className="flex flex-wrap items-start justify-between gap-3 mb-4">
        <div>
          <h2 className="text-lg font-semibold text-stone-900">Come conservarla</h2>
          <p className="text-xs text-stone-400 mt-0.5">Consigli dell’IA sul piatto pronto</p>
        </div>
        {hasData && onGenerate ? (
          <button
            type="button"
            className="btn-secondary !py-2 !px-3 text-sm"
            onClick={onGenerate}
            disabled={loading}
            aria-busy={loading}
          >
            {loading ? 'Aggiorno…' : 'Rigenera'}
          </button>
        ) : null}
      </div>

      {error && (
        <p className="mb-3 text-sm text-red-600" role="alert">
          {error}
        </p>
      )}

      {!hasData ? (
        pending || loading ? (
          <p className="text-sm text-stone-500" aria-live="polite">
            Sto chiedendo a Gemini come conservarla…
          </p>
        ) : (
          <div className="flex flex-wrap items-center gap-3">
            <p className="text-sm text-stone-500">Nessun consiglio ancora per questa ricetta.</p>
            {onGenerate ? (
              <button type="button" className="btn-primary !py-2.5 !px-4 text-sm" onClick={onGenerate}>
                Chiedi a Gemini
              </button>
            ) : null}
          </div>
        )
      ) : (
        <>
          {storage.warning ? (
            <p className="mb-4 rounded-xl border border-amber-200 bg-amber-50 px-3.5 py-2.5 text-sm text-amber-900 leading-relaxed">
              <span className="font-semibold">Attenzione: </span>
              {storage.warning}
            </p>
          ) : null}

          <div className="grid grid-cols-1 sm:grid-cols-3 gap-3">
            {PLACES.map(({ key, label, icon }) => {
              const p = storage[key] || {}
              const ok = p.ok !== false && (p.duration || p.how)
              return (
                <div
                  key={key}
                  className={`rounded-2xl border p-4 ${
                    ok ? 'border-teal-100 bg-teal-50/50' : 'border-stone-200 bg-stone-50'
                  }`}
                >
                  <div className={`flex items-center gap-2 ${ok ? 'text-teal-800' : 'text-stone-400'}`}>
                    {icon}
                    <h3 className="text-sm font-semibold">{label}</h3>
                  </div>
                  <p className={`mt-2 text-base font-semibold ${ok ? 'text-stone-900' : 'text-stone-500'}`}>
                    {ok ? p.duration || 'Sì' : 'Sconsigliato'}
                  </p>
                  {p.how ? <p className="mt-1 text-sm text-stone-600 leading-relaxed">{p.how}</p> : null}
                  {key === 'freezer' && ok && p.thaw ? (
                    <p className="mt-2 text-sm text-stone-600 leading-relaxed">
                      <span className="font-medium text-stone-700">Scongelare: </span>
                      {p.thaw}
                    </p>
                  ) : null}
                </div>
              )
            })}
          </div>

          {storage.reheat ? (
            <p className="mt-4 text-sm text-stone-700 leading-relaxed">
              <span className="font-semibold text-stone-900">Per riscaldare: </span>
              {storage.reheat}
            </p>
          ) : null}

          {storage.tips?.length ? (
            <ul className="mt-3 space-y-1.5">
              {storage.tips.map((tip) => (
                <li key={tip} className="flex gap-2 text-sm text-stone-600 leading-relaxed">
                  <span className="text-primary shrink-0" aria-hidden>
                    •
                  </span>
                  <span>{tip}</span>
                </li>
              ))}
            </ul>
          ) : null}

          <p className="mt-4 text-xs text-stone-400">
            Indicazioni generali generate dall’IA: nel dubbio controlla aspetto e odore prima di consumare.
          </p>
        </>
      )}
    </section>
  )
}
